import json, os, collections, re

def parse_years(raw):
    """从年代串粗解析窗口：前N世纪 / 前N年 / N世纪 / N年 → (y0,y1)。
    只用于条目筛选窗口，不冒充精确纪年；含「约」「—」一律标 range。"""
    pts = []
    for m in re.finditer(r'(前)?(\d+)(世纪|年)?', raw):
        pre, n, unit = m.group(1), int(m.group(2)), m.group(3)
        if unit == '世纪':
            v = -n * 100 if pre else (n - 1) * 100 + 1
        else:
            v = -n if pre else n
        pts.append(v)
    if not pts:
        return -3000, 2000
    y0 = min(pts)
    y1 = 2026 if '今' in raw else (max(pts) if len(pts) > 1 else min(2026, y0 + 2000))
    if y1 < y0: y0, y1 = y1, y0
    return max(-10000, y0), min(2026, y1)

