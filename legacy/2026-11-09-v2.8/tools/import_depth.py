def src(kind='general'):
    base = {'general': [(BRIT, '百科／媒体'), (WIKI, '百科／媒体')],
            'china': [(BRIT, '百科／媒体'), (CSSN, '机构／学术')],
            'unesco': [(BRIT, '百科／媒体'), (UNES, '机构／学术')]}[kind]
    return [{'url': u, 'quote': '', 'rank': r,
             'note': '域名级检索入口，非具体引文页；本轮未逐条附引文'} for u, r in base]

def item(iid, title, raw, y0, y1, cat, summary, boundary='', region='*',
         precision='range', consensus='settled', sk='general', extra=None):
    o = dict(id=iid, title=title, rawYear=raw, y0=y0, y1=y1, category=cat,
             summary=summary, boundary=boundary, region=region,
             precision=precision, consensus=consensus, sources=src(sk))
    if extra: o.update(extra)
    return o

