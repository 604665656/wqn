# 知识全景六大知识类 + 第七类「边界与分层」（不设维度，只在文档与狂想档里）。
# 分类是约定性的：主归类不排斥跨类，例如历法既属自然基底也属认知方法。
FAMILIES = ['自然基底','物质生产','社会组织','符号与意义','交换网络','认知方法','边界与分层']
FAMILY = {}
def _fam(fam, keys):
    for k in keys.split():
        assert k not in FAMILY, '重复归类 '+k
        FAMILY[k] = fam
